// tools/build-helper-knowledge.js — run: node tools/build-helper-knowledge.js
// Writes worker/src/knowledge.js, what Bob's helper (phase 2) knows: docs/llms.txt (Bob's own words, hours, phones,
// towns) plus each service page's description from dist/btg.js. Re-run after editing either; test/helper-knowledge.test.js
// fails while the file is stale. The Virginia street address is in neither source and must never be added.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');

function build() {
  global.window = global.window || global;
  require(path.join(root, 'dist/btg.js'));
  const pages = window.BTGSearch.PAGES.filter((p) => p.type === 'SERVICE');
  const services = pages.map((p) => {
    const slug = p.url.replace('https://bobthetechguy.com/', '').replace(/\/$/, '');
    return { slug, title: p.title, desc: window.BTGInit.DESCRIPTIONS['/' + slug + '/'] };
  });
  const llms = fs.readFileSync(path.join(root, 'docs/llms.txt'), 'utf8').replace(/\r\n/g, '\n').trim();
  const knowledge = llms + '\n\n## Service pages (slug: description)\n\n' + services.map((s) => '- ' + s.slug + ' (' + s.title + '): ' + s.desc).join('\n');
  return '// Generated by tools/build-helper-knowledge.js from docs/llms.txt and dist/btg.js. Do not edit by hand.\n' +
    'export const SERVICE_SLUGS = ' + JSON.stringify(services.map((s) => s.slug)) + ';\n' +
    'export const KNOWLEDGE = ' + JSON.stringify(knowledge) + ';\n';
}

module.exports = { build, OUT: path.join(root, 'worker/src/knowledge.js') };
if (require.main === module) { fs.writeFileSync(module.exports.OUT, build()); console.log('wrote', module.exports.OUT); }
